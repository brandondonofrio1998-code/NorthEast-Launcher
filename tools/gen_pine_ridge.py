#!/usr/bin/env python3
"""Generates the home screen's static pine-ridge art as three layered vector drawables:

    app/src/main/res/drawable/pine_ridge_far.xml
    app/src/main/res/drawable/pine_ridge_mid.xml
    app/src/main/res/drawable/pine_ridge_near.xml

Each layer is a single white silhouette; the app tints it at runtime with that layer's seasonal
color (see Woodland.ridgeColors in ui/theme/Theme.kt). All three share one viewport, so they line
up when stacked.

Original artwork for this project (see ASSETS.md). Deterministic: the same seed always produces
the same files, so they can be regenerated and reviewed in diffs.

    python3 tools/gen_pine_ridge.py app/src/main/res/drawable
"""
import math
import os
import random
import sys

W, H = 1920, 360
SEED = 1788  # arbitrary, fixed

# Far → near. Order matters: the random sequence (and so every tree) depends on it.
LAYERS = [
    # name, ground y, hill amplitude, tree height range, tree spacing range
    ("far", 250, 18, (60, 110), (34, 58)),
    ("mid", 285, 14, (90, 150), (46, 80)),
    ("near", 320, 10, (120, 200), (70, 120)),
]


def ground(x, base, amp, phase):
    return base + amp * math.sin(x / 260.0 + phase) + amp * 0.5 * math.sin(x / 97.0 + phase * 2)


def tree(cx, gy, h):
    """A three-tier pine, outlined clockwise (screen coords) so nonZero fill unions cleanly."""
    w = h * 0.55
    trunk_w, trunk_h = w * 0.10, h * 0.07
    pts = [
        (cx - trunk_w, gy + 2),
        (cx - trunk_w, gy - trunk_h),
        (cx - w * 0.50, gy - trunk_h),
        (cx - w * 0.22, gy - h * 0.38),
        (cx - w * 0.36, gy - h * 0.38),
        (cx - w * 0.14, gy - h * 0.68),
        (cx - w * 0.24, gy - h * 0.68),
        (cx, gy - h),
        (cx + w * 0.24, gy - h * 0.68),
        (cx + w * 0.14, gy - h * 0.68),
        (cx + w * 0.36, gy - h * 0.38),
        (cx + w * 0.22, gy - h * 0.38),
        (cx + w * 0.50, gy - trunk_h),
        (cx + trunk_w, gy - trunk_h),
        (cx + trunk_w, gy + 2),
    ]
    return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"


def layer_path(rng, base, amp, heights, spacing):
    phase = rng.uniform(0, math.tau)
    # Ground band: follows the hill curve, closed along the bottom edge (clockwise).
    xs = list(range(0, W + 1, 40))
    d = [f"M0,{ground(0, base, amp, phase):.1f}"]
    d += [f"L{x},{ground(x, base, amp, phase):.1f}" for x in xs[1:]]
    d.append(f"L{W},{H} L0,{H} Z")
    x = rng.uniform(-20, spacing[0])
    while x < W + 40:
        d.append(tree(x, ground(x, base, amp, phase), rng.uniform(*heights)))
        x += rng.uniform(*spacing)
    return " ".join(d)


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "app/src/main/res/drawable"
    rng = random.Random(SEED)
    for name, base, amp, heights, spacing in LAYERS:
        path = layer_path(rng, base, amp, heights, spacing)
        xml = "\n".join([
            '<?xml version="1.0" encoding="utf-8"?>',
            "<!-- Generated by tools/gen_pine_ridge.py. Original artwork; see ASSETS.md. Do not edit by hand. -->",
            f"<!-- {name} ridge layer: white silhouette, tinted at runtime with the seasonal color. -->",
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
            f'    android:width="{W // 2}dp"',
            f'    android:height="{H // 2}dp"',
            f'    android:viewportWidth="{W}"',
            f'    android:viewportHeight="{H}">',
            f'    <path android:fillColor="#FFFFFFFF" android:pathData="{path}" />',
            "</vector>",
            "",
        ])
        with open(os.path.join(out_dir, f"pine_ridge_{name}.xml"), "w") as f:
            f.write(xml)


if __name__ == "__main__":
    main()
